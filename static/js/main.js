// ==== 滚动触发 reveal(IntersectionObserver + stagger 入场) ====
(function initReveal() {
    const revealEls = document.querySelectorAll('[data-reveal]');
    if (!revealEls.length) return;

    if (PREFERS_REDUCED_MOTION || !('IntersectionObserver' in window)) {
        revealEls.forEach(el => el.classList.add('is-visible'));
        return;
    }

    const io = new IntersectionObserver((entries) => {
        // 同批进入视口的元素依次延迟 70ms,封顶 490ms
        const visible = entries.filter(e => e.isIntersecting);
        visible.forEach((entry, i) => {
            entry.target.style.setProperty('--reveal-delay', `${Math.min(i, 7) * 70}ms`);
            entry.target.classList.add('is-visible');
            io.unobserve(entry.target);
        });
    }, { threshold: 0.1, rootMargin: '0px 0px -6% 0px' });

    revealEls.forEach(el => io.observe(el));
})();

// ==== 数字滚动动画 ====
document.querySelectorAll('[data-countup]').forEach(el => {
    const target = parseInt(el.textContent.replace(/\D/g, ''), 10) || 0;
    // 不动画时(含后台标签页 rAF 被节流的情况)直接落定到目标值,
    // 把首帧写入也放进 rAF:这样若 rAF 永不触发,元素会保留服务端渲染的真实数字而非停在 0
    if (PREFERS_REDUCED_MOTION || target === 0 || document.hidden) {
        el.textContent = target;
        return;
    }
    const duration = 900;
    let startTs = null;
    function step(ts) {
        if (startTs === null) startTs = ts;
        const p = Math.min((ts - startTs) / duration, 1);
        el.textContent = Math.round(target * (1 - Math.pow(1 - p, 3)));
        if (p < 1) requestAnimationFrame(step);
    }
    requestAnimationFrame(step);
});

// ==== 页面顶部阅读进度条 ====
(function initProgressBar() {
    const bar = document.getElementById('progress-bar');
    if (!bar) return;
    let ticking = false;
    function update() {
        const doc = document.documentElement;
        const max = doc.scrollHeight - doc.clientHeight;
        bar.style.transform = `scaleX(${max > 0 ? doc.scrollTop / max : 0})`;
        ticking = false;
    }
    document.addEventListener('scroll', () => {
        if (!ticking) {
            ticking = true;
            requestAnimationFrame(update);
        }
    }, { passive: true });
    update();
})();

