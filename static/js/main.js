const UPLOAD_IMAGE_EXT = ['png', 'jpg', 'jpeg', 'gif', 'webp'];
const UPLOAD_DOC_EXT = ['md', 'txt', 'pdf'];

// 供提交逻辑读取:已上传成功的附件 id 列表
